export function tx(lang: Lang, key: string, params: Record<string, string | number> = {}) {
  const raw = DICTS[lang]?.[key] ?? en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : `{${k}}`));
}

