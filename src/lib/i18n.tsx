const DICTS: Record<Lang, Partial<Record<Key, string>>> = { en, nl, de: deL.ui as Partial<Record<Key, string>>, es: esL.ui as Partial<Record<Key, string>>, ko: koL.ui as Partial<Record<Key, string>> };

export type TFn = (k: Key, p?: Record<string, string | number>) => string;

interface Ctx {
  lang: Lang;
  units: Units;
  setLang: (l: Lang) => void;
  setUnits: (u: Units) => void;
  t: TFn;
  pace: (secPerKm: number | null | undefined) => string;
  dist: (km: number) => string;
  kg: (kg: number) => string;
}

const I18n = createContext<Ctx>(null as unknown as Ctx);

const read = <T extends string>(k: string, d: T): T => {
  try {
    return (localStorage.getItem(k) as T) || d;
  } catch {
    return d;
  }
};

const UI_LANGS: Lang[] = ['en', 'nl', 'de', 'es', 'ko'];
const COUNTRY_LANG: Record<string, Lang> = {
  NL: 'nl', BE: 'nl', SR: 'nl', AW: 'nl', CW: 'nl', SX: 'nl', BQ: 'nl',
  DE: 'de', AT: 'de', CH: 'de', LI: 'de', LU: 'de',
  ES: 'es', MX: 'es', AR: 'es', CO: 'es', CL: 'es', PE: 'es', VE: 'es', EC: 'es', GT: 'es', CU: 'es', BO: 'es', DO: 'es', HN: 'es', PY: 'es', SV: 'es', NI: 'es', CR: 'es', PA: 'es', UY: 'es', PR: 'es',
  KR: 'ko',
};
const store = (k: string, v: string) => {
  try {
    localStorage.setItem(k, v);
  } catch {
    /* ignore */
  }
};
/** Language order: ?lang= in the link > a choice the user made > the country of their IP > the browser language. */
function initialLang(): { lang: Lang; chosen: boolean } {
  try {
    const q = new URLSearchParams(window.location.search).get('lang')?.toLowerCase() as Lang | undefined;
    if (q && UI_LANGS.includes(q)) {
      store('rox:lang', q);
      return { lang: q, chosen: true };
    }
  } catch {
    /* ignore */
  }
  const saved = read('rox:lang', '' as Lang);
  if (UI_LANGS.includes(saved)) return { lang: saved, chosen: true };
  const geo = COUNTRY_LANG[read('rox:geo', '')];
  if (geo) return { lang: geo, chosen: false };
  const nav = typeof navigator !== 'undefined' ? navigator.language?.slice(0, 2) : 'en';
  return { lang: (UI_LANGS.includes(nav as Lang) ? nav : 'en') as Lang, chosen: false };
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [init] = useState(initialLang);
  const [lang, setLangState] = useState<Lang>(init.lang);
  useEffect(() => {
    if (init.chosen) return;
    let alive = true;
    fetch('/api/geo')
      .then((r) => (r.ok ? r.json() : null))
      .then((j: { country?: string | null } | null) => {
        if (!alive || !j?.country) return;
        store('rox:geo', j.country);
        const g = COUNTRY_LANG[j.country];
        // only switch if the user hasn't picked a language in the meantime
        if (g && !read('rox:lang', '')) setLangState(g);
      })
      .catch(() => undefined);
    return () => {
      alive = false;
    };
  }, [init.chosen]);
  const [units, setUnitsState] = useState<Units>(() => read('rox:units', 'metric'));
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem('rox:lang', l);
    } catch {
      /* ignore */
    }
  };
  const setUnits = (u: Units) => {
    setUnitsState(u);
    try {
      localStorage.setItem('rox:units', u);
    } catch {
      /* ignore */
    }
  };
  const t: TFn = (k, p = {}) =>
    (DICTS[lang][k] ?? en[k] ?? k).replace(/\{(\w+)\}/g, (_, x) => (p[x] !== undefined ? String(p[x]) : ''));
  const imperial = units === 'imperial';
  const pace = (s: number | null | undefined) => (s == null ? '–' : imperial ? `${fmtMmss(s * 1.609344)}/mi` : `${fmtMmss(s)}/km`);
  const dist = (km: number) => (imperial ? `${(km / 1.609344).toFixed(1)} mi` : `${km} km`);
  const kg = (v: number) => (imperial ? `${Math.round(v * 2.20462)} lb` : `${v} kg`);
  return <I18n.Provider value={{ lang, units, setLang, setUnits, t, pace, dist, kg }}>{children}</I18n.Provider>;
}

export const useI18n = () => useContext(I18n);
